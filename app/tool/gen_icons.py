"""Collects every inline SVG icon from the design boards into lib/core/icons/icon_data.dart.
Run from app/: python3 tool/gen_icons.py   (icons are named by a short hash of their markup;
friendly names live in lib/core/icons/app_icons.dart)."""
import glob, hashlib, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
BOARDS = os.path.join(HERE, '..', '..', 'design', 'screens')
icons = {}
for f in sorted(glob.glob(os.path.join(BOARDS, '*.dc.html'))):
    s = open(f, encoding='utf-8').read()
    for attrs, inner in re.findall(r'<svg([^>]*)>(.*?)</svg>', s, flags=re.S):
        inner = inner.strip()
        if 'data:' in inner or len(inner) > 6000:
            continue
        h = hashlib.md5(inner.encode()).hexdigest()[:6]
        vb = re.search(r'viewBox="([^"]+)"', attrs)
        icons.setdefault(h, (vb.group(1) if vb else '0 0 24 24', inner))

out = ['// GENERATED by tool/gen_icons.py from design/screens. Do not edit by hand.\n',
       "import 'app_icon.dart';\n\n", 'abstract final class Ic {\n']
for h, (vb, inner) in sorted(icons.items()):
    esc = inner.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', ' ')
    out.append(f"  static const i{h} = AppIconData('{vb}', '{esc}');\n")
out.append('}\n')
open(os.path.join(HERE, '..', 'lib', 'core', 'icons', 'icon_data.dart'), 'w').write(''.join(out))
print(len(icons), 'icons')
